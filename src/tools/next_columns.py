"""路线图上节点之间的连接。"""


def next_columns(map_type: str, row: int, col: int) -> tuple[int, ...]:
    """地图上第 row 层第 col 列的节点能走到下一层的哪几列。起点（第 0 层）固定能走到第 1 层的 0、1 两列。"""
    if row == 0:
        return 0, 1
    links: dict[str, dict[tuple[int, int], tuple[int, ...]]] = {
        "2x3": {
            (1, 0): (0, 1),
            (1, 1): (1, 2, 3),
            (2, 0): (0, 1, 2),
            (2, 1): (0, 1, 2),
            (2, 2): (2, 3),
            (2, 3): (2, 3),
        },
        "3x2": {
            (1, 0): (0, 1, 2),
            (1, 1): (2, 3),
            (2, 0): (0, 1),
            (2, 1): (0, 1),
            (2, 2): (0, 1),
            (2, 3): (1, 2, 3),
        },
        "2x2": {
            (1, 0): (0, 1),
            (1, 1): (2, 3),
            (2, 0): (0, 1),
            (2, 1): (1, 2, 3),
            (2, 2): (1, 2, 3),
            (2, 3): (1, 2, 3),
        },
    }
    return links[map_type][(row, col)]
