def _type_multiplier(move_type: str, defender_types: Iterable[str]) -> float:
    """招式属性打防守方属性的倍率，双属性相乘。"""
    multiplier = 1.0
    for defender_type in defender_types:
        multiplier *= TYPE_CHART[TYPE_ORDER.index(move_type)][TYPE_ORDER.index(defender_type)]
    return multiplier


def move_score(own: dict, opponent: dict, move: dict) -> float:
    """用威力、本系加成和属性相克给招式打分。"""
    if move["category"] == "status" or move["power"] <= 0:
        return 0.0
    stab = 1.5 if move["type_id"] in own["type_ids"] else 1.0
    return move["power"] * stab * _type_multiplier(move["type_id"], opponent["type_ids"])
